// Helper function to get products by category
export const getProductsByCategory = (category) => {
  if (category === 'All products' || !category) {
    return mockProducts
  }
  if (category === 'Best Sellers') {
    return mockProducts.filter((p) => p.discount > 0).slice(0, 6)
  }
  return mockProducts.filter((p) => p.category === category)
}

// Get unique colors and sizes
export const getUniqueColors = () => {
  return [...new Set(mockProducts.map((p) => p.color))]
}

export const getUniqueSizes = () => {
  return [...new Set(mockProducts.map((p) => p.size))]
}

